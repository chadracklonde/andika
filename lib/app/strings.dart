import 'dart:ui' show PlatformDispatcher;

/// Textes de l'interface, en français et en anglais. Pas de dépendance externe :
/// une table par langue, des paramètres `{nom}` remplacés à l'affichage.
class Strings {
  Strings._(this.languageCode, this._table);

  final String languageCode;
  final Map<String, String> _table;

  /// [setting] : `fr`, `en` ou `system` (suit la langue du téléphone, français par défaut).
  static Strings forSetting(String setting) {
    var code = setting;
    if (code != 'fr' && code != 'en') {
      code = PlatformDispatcher.instance.locale.languageCode == 'en' ? 'en' : 'fr';
    }
    return Strings._(code, code == 'en' ? kStringsEn : kStringsFr);
  }

  static Strings forCode(String code) =>
      Strings._(code == 'en' ? 'en' : 'fr', code == 'en' ? kStringsEn : kStringsFr);

  bool has(String key) => _table.containsKey(key);

  String t(String key, [Map<String, String>? args]) {
    var text = _table[key] ?? key;
    if (args != null) {
      args.forEach((k, v) => text = text.replaceAll('{$k}', v));
    }
    return text;
  }
}

